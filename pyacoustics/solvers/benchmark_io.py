def write_benchmark_rows_csv(
    path: str | Path,
    rows: list[BenchmarkRow] | tuple[BenchmarkRow, ...],
    *,
    fieldnames: list[str] | tuple[str, ...] | None = None,
) -> Path:
    """Write flattened benchmark rows to CSV and return the output path."""

    output = Path(path)
    output.parent.mkdir(parents=True, exist_ok=True)
    columns = tuple(fieldnames) if fieldnames is not None else benchmark_fieldnames(rows)
    with output.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns, extrasaction="ignore", lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow(row)
    return output


def write_benchmark_rows_json(
    path: str | Path,
    rows: list[BenchmarkRow] | tuple[BenchmarkRow, ...],
    *,
    indent: int = 2,
) -> Path:
    """Write flattened benchmark rows to UTF-8 JSON and return the output path."""

    output = Path(path)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(list(rows), ensure_ascii=False, indent=indent) + "\n", encoding="utf-8")
    return output


