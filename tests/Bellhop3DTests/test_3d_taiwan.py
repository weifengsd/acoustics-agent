def resolve_at_bin():
    """Helper to resolve Acoustics Toolbox binary path."""
    dummy_solver = BellhopExternal(None)
    assert dummy_solver.bin_path is not None
    return dummy_solver.bin_path

@pytest.fixture
def taiwan_env():
    """
    Pytest fixture to manage file copies and cleanups for Taiwan runs.
    Ensures that temporary .bty and .ssp file copies are cleaned up after runs.
    """
    target_dir = Path(__file__).resolve().parent / "Taiwan"

    # Files generated by the runs
    cleanup_extensions = ["*.ray", "*.prt", "*.shd", "*.bty", "*.ssp"]

    def cleanup():
        # Specifically delete files with prefix Taiwan and the standard cleanup extensions
        for ext in cleanup_extensions:
            for f in target_dir.glob(ext):
                # Do not delete the original Taiwan.bty and Taiwan.ssp
                if f.name in ["Taiwan.bty", "Taiwan.ssp"]:
                    continue
                try:
                    f.unlink()
                except OSError:
                    pass

    # Pre-test cleanup
    cleanup()
    yield target_dir
    # Post-test cleanup
    cleanup()

def test_taiwan_nx2d_ray_tracing(taiwan_env):
    """
    Nx2D Ray Tracing Integration Test:
    1. Copies the bathymetry and SSP database for Nx2D run.
    2. Runs Bellhop3D on TaiwanNx2D_ray.env.
    3. Verifies that the .ray file is produced and parses successfully in 3D.
    """
    target_dir = taiwan_env
    bin_path = resolve_at_bin()

    bellhop3d_exe = bin_path / "bellhop3d"
    if not bellhop3d_exe.exists():
        bellhop3d_exe = bin_path / "bellhop3d.exe"

    assert bellhop3d_exe.exists(), "bellhop3d native executable not found."

    fileroot = "TaiwanNx2D_ray"

    # 1. Setup temporary database copies matching AT's original runtests.m logic
    shutil.copy(target_dir / "Taiwan.bty", target_dir / f"{fileroot}.bty")
    shutil.copy(target_dir / "Taiwan.ssp", target_dir / f"{fileroot}.ssp")

    # 2. Execute Legacy Bellhop3D Process
    print(f"\n[Taiwan] Running bellhop3d on {fileroot}...")
    res = subprocess.run(
        [str(bellhop3d_exe), fileroot],
        cwd=str(target_dir),
        capture_output=True,
        text=True
    )
    assert res.returncode == 0, f"Bellhop3D run failed for {fileroot}: {res.stderr}"

    # 3. Read and Parse the Output Ray File
    ray_file = target_dir / f"{fileroot}.ray"
    assert ray_file.exists(), f"Output ray file {fileroot}.ray was not generated."
    assert ray_file.stat().st_size > 100, "Generated ray file is empty."

    rays = read_at_ray(str(ray_file))
    assert len(rays) > 0, "Parsed ray trajectory list should not be empty."

    # 4. Check a few rays for spatial structure
    for ray in rays[:5]:
        c1, c2, c3 = ray
        assert len(c1) > 0, "Ray coordinate list must contain active points"
        assert len(c2) == len(c1)
        assert len(c3) == len(c1)

    print(f"🏆 [Taiwan] Nx2D Ray Tracing verified. Traced {len(rays)} active rays successfully!")

def test_taiwan_3d_ray_tracing(taiwan_env):
    """
    Full 3D Ray Tracing Integration Test:
    1. Copies bathymetry and SSP for 3D run (rays bend laterally over sloping bathymetry).
    2. Runs Bellhop3D on Taiwan3D_ray.env.
    3. Parses and validates the full 3D coordinates.
    """
    target_dir = taiwan_env
    bin_path = resolve_at_bin()

    bellhop3d_exe = bin_path / "bellhop3d"
    if not bellhop3d_exe.exists():
        bellhop3d_exe = bin_path / "bellhop3d.exe"

    fileroot = "Taiwan3D_ray"

    # 1. Setup temporary database copies
    shutil.copy(target_dir / "Taiwan.bty", target_dir / f"{fileroot}.bty")
    shutil.copy(target_dir / "Taiwan.ssp", target_dir / f"{fileroot}.ssp")

    # 2. Execute Legacy Bellhop3D Process
    print(f"\n[Taiwan] Running bellhop3d on {fileroot}...")
    res = subprocess.run(
        [str(bellhop3d_exe), fileroot],
        cwd=str(target_dir),
        capture_output=True,
        text=True
    )
    assert res.returncode == 0, f"Bellhop3D run failed for {fileroot}: {res.stderr}"

    # 3. Read and Parse the 3D Ray File
    ray_file = target_dir / f"{fileroot}.ray"
    assert ray_file.exists(), f"Output ray file {fileroot}.ray was not generated."

    rays = read_at_ray(str(ray_file))
    assert len(rays) > 0, "Parsed 3D ray list should not be empty."

    # 4. Core physical validation of 3D kinematics (lateral ray deviation)
    # In 3D ray tracing, rays should have non-zero y-coordinates (c2 in csh/Matlab)
    has_lateral_deviation = False
    for ray in rays:
        c1, c2, c3 = ray  # For 3D: c1 is x, c2 is y, c3 is z
        # Check if the ray deviated from the straight azimuth line
        # Depending on source coordinate and azimuth, we check relative lateral movement
        if any(abs(y - c2[0]) > 1e-3 for y in c2[1:]):
            has_lateral_deviation = True
            break

    assert has_lateral_deviation, "3D ray tracing should yield non-zero lateral deviation over Taiwan terrain."

    print(f"🏆 [Taiwan] Full 3D Ray Tracing verified. Lateral Snells deviation detected. Traced {len(rays)} rays!")

def test_native_taiwan_3d_ray_tracing(taiwan_env):
    """
    Native Full 3D Ray Tracing Test:
    1. Loads the bathymetry natively with proper Fortran reshaping.
    2. Runs PyBellhop3D natively.
    3. Validates the full 3D coordinates exhibit lateral Snell's deviation.
    """
    from pyacoustics.simulation import Simulation
    import numpy as np

    # Custom BTY parser strictly matching Fortran column-major storage
    def load_bty_3d(filename):
        with open(filename, 'r') as f:
            lines = f.readlines()
        nx = int(lines[1].strip())
        x_bounds = [float(x) for x in lines[2].replace('/', '').split() if x.strip()]
        if len(x_bounds) == 2:
            x_grid = np.linspace(x_bounds[0], x_bounds[1], nx) * 1000.0
        else:
            x_grid = np.array(x_bounds) * 1000.0

        ny = int(lines[3].strip())
        y_bounds = [float(y) for y in lines[4].replace('/', '').split() if y.strip()]
        if len(y_bounds) == 2:
            y_grid = np.linspace(y_bounds[0], y_bounds[1], ny) * 1000.0
        else:
            y_grid = np.array(y_bounds) * 1000.0

        z_vals = []
        for line in lines[5:]:
            z_vals.extend([float(v) for v in line.replace('/', '').split() if v.strip()])

        z_grid = np.array(z_vals[:nx*ny]).reshape((ny, nx)).T
        return x_grid, y_grid, z_grid

    sim = Simulation("tests/Munk/munk_3d_terrain.yaml")

    # Source position based on Taiwan3D_ray.env (x=175km, y=200km)
    sim.config.frequency = 250.0
    sim.config.solver.num_elevation_beams = 10
    sim.config.solver.elevation_angles = [-20.0, 20.0]
    sim.config.solver.num_azimuth_beams = 36
    sim.config.solver.azimuth_angles = [0.0, 350.0]
    sim.config.geometry.source.depths = [100.0]

    tw_dir = taiwan_env
    bx, by, bz = load_bty_3d(str(tw_dir / 'Taiwan.bty'))

    # Offset by source coordinate (175km, 200km)
    sim.config.environment.bottom.bathymetry_3d.x = (bx - 175000.0).tolist()
    sim.config.environment.bottom.bathymetry_3d.y = (by - 200000.0).tolist()
    sim.config.environment.bottom.bathymetry_3d.z = bz.tolist()

    from pyacoustics.solvers.bellhop3d.core import PyBellhop3D
    solver = PyBellhop3D(sim.config)
    rays_3d = solver.run_ray_tracing()

    assert len(rays_3d) > 0, "Native ray tracer must yield active rays"

    has_lateral_deviation = False
    for ray in rays_3d:
        (
            x_path, y_path, z_path,
            q11, q12, q21, q22,
            amp, tau, kmah, cpath,
            n_top, n_bot, elev
        ) = ray

        # Calculate theoretical straight line path
        # If it deviates from a straight line in the x-y plane, it's 3D refraction
        if len(x_path) > 2:
            dx = x_path[-1] - x_path[0]
            dy = y_path[-1] - y_path[0]
            if dx != 0:
                expected_y = y_path[0] + (x_path[1:-1] - x_path[0]) * (dy / dx)
                if any(abs(y_path[1:-1] - expected_y) > 1.0):
                    has_lateral_deviation = True
                    break

    assert has_lateral_deviation, "Native 3D ray tracing should yield non-zero lateral deviation over the Taiwan terrain."

    print(f"🏆 [Taiwan Native] Full 3D Ray Tracing verified. Traced {len(rays_3d)} rays!")